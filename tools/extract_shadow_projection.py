#!/usr/bin/env python3
"""Recover the fixed word ranges in the original ground projection routine."""

import argparse
from pathlib import Path
import struct


def recover(program: bytes) -> list[tuple[int, int, bool]]:
    memory = bytes(0x600) + program
    pc, base = 0xB00A, 0
    groups = []
    current = None
    while pc <= 0xB704:
        opcode = struct.unpack_from(">H", memory, pc)[0]
        if opcode == 0x2078 and memory[pc + 2:pc + 4] == b"\x06\x38":
            base, pc = 0, pc + 4
        elif opcode == 0x41E8:
            base += struct.unpack_from(">h", memory, pc + 2)[0]
            pc += 4
        elif opcode == 0x3028:
            if current is not None:
                groups.append(current)
            current = {"load": base + struct.unpack_from(">h", memory, pc + 2)[0], "words": []}
            pc += 4
        elif opcode in (0xE248, 0xE348) and current is not None:
            current["left"] = opcode == 0xE248
            pc += 2
        elif opcode in (0xE5E8, 0xE4E8) and current is not None:
            if current["left"] != (opcode == 0xE5E8):
                raise ValueError(f"Unexpected rotation direction at {pc:#x}")
            current["words"].append(base + struct.unpack_from(">h", memory, pc + 2)[0])
            pc += 4
        elif opcode == 0xE0E8:
            if current is not None:
                groups.append(current)
            address = base + struct.unpack_from(">h", memory, pc + 2)[0]
            current = {"load": address, "words": [address], "left": False}
            pc += 4
        elif opcode == 0x4E75 and pc == 0xB704:
            if current is not None:
                groups.append(current)
            break
        else:
            raise ValueError(f"Unexpected projection instruction {opcode:#x} at {pc:#x}")
    result = []
    for group in groups:
        words, left = group["words"], group["left"]
        step = -2 if left else 2
        if not words or words[0] != group["load"] or words != list(range(words[0], words[-1] + step, step)):
            raise ValueError(f"Unexpected projection word range: {group}")
        if any(not 0x7800 <= address < 0x7D00 or address % 160 >= 40 for address in words):
            raise ValueError("Projection escaped the ground's first bitplane")
        result.append((words[0], words[-1], left))
    if len(result) != 78:
        raise ValueError("Unexpected original projection group count")
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--game", type=Path, default=Path("assets/original/game.bin"))
    parser.add_argument("--out", type=Path, default=Path("internal/presentation/shadow_projection_data.go"))
    args = parser.parse_args()
    groups = recover(args.game.read_bytes())
    text = "// Code generated by tools/extract_shadow_projection.py; DO NOT EDIT.\n\npackage presentation\n\n"
    text += "// These fixed ranges translate the packed ground projection at $B00A.\n"
    text += "var shadowProjection = [...]struct {\n\tfirst, last int\n\tleft        bool\n}{\n"
    for first, last, left in groups:
        text += f"\t{{0x{first:04x}, 0x{last:04x}, {str(left).lower()}}},\n"
    text += "}\n"
    args.out.write_text(text)
    print(f"Recovered {len(groups)} original ground projection ranges: {args.out}")


if __name__ == "__main__":
    main()
